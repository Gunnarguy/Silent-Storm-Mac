"""Generate trivially-implemented base classes for every Direct3D 9 interface in win/d3d9.h."""
import re, sys
src = open('port/platform/include/win/d3d9.h').read()
out = ['// generated by port/tools/gen_d3d9_stubs.py from include/win/d3d9.h -- do not edit',
       '#pragma once', '#include "s2com.h"', 'void S2Unimplemented(const char *what);', '#include "win/d3d9.h"', 'namespace s2gfx {']
for m in re.finditer(r'DECLARE_INTERFACE_IID_\((\w+),\s*(\w+),[^)]*\)\s*\{(.*?)\};', src, re.S):
    name, base, body = m.group(1), m.group(2), m.group(3)
    out.append(f'struct Stub{name} : public {name}\n{{')
    for mm in re.finditer(r'STDMETHOD(_?)\(([^)]*)\)\s*\(THIS_?\s*(.*?)\)\s*PURE;', body, re.S):
        under, inner, args = mm.groups()
        if under:
            rtype, meth = [x.strip() for x in inner.split(',', 1)]
        else:
            rtype, meth = 'HRESULT', inner.strip()
        if meth in ('QueryInterface', 'AddRef', 'Release'):
            continue
        args = ' '.join(args.split())
        # give unnamed parameters no names; keep named ones (unused warnings are off)
        if rtype == 'HRESULT': ret = 'return E_NOTIMPL;'
        elif rtype == 'void': ret = ''
        elif rtype.endswith('*'): ret = 'return 0;'
        else: ret = f'return ({rtype})0;'
        out.append(f'\t{rtype} {meth}({args}) override {{ S2Unimplemented("{name}::{meth}"); {ret} }}')
    out.append('};')
out.append('} // namespace s2gfx')
open('port/platform/src/gen/d3d9_stubs.h', 'w').write('\n'.join(out) + '\n')
print('interfaces:', src.count('DECLARE_INTERFACE_IID_'))
