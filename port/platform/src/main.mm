// First launch in a game folder: write settings tuned for this Mac once (the in-game Options menu owns them
// afterwards). Resolution is the screen's "looks like" size so the 2003 interface reads at its designed scale;
// MetalFX upscales the image to the panel's native pixels. Every quality option is at its highest setting.
static void S2WriteMacDefaults(const std::string &dir)
{
	std::string marker = dir + "/cfg/.macos-defaults-v1";
	struct stat st;
	if (stat(marker.c_str(), &st) == 0) return;
	NSRect f = NSScreen.mainScreen.frame;
	int w = (int)f.size.width, h = (int)f.size.height;
	std::string cfg = "//============================================================================\r\n// generated by S^2, do not modify\r\n//============================================================================\r\n";
	char line[160];
	snprintf(line, sizeof line, "setvar gfx_resolution = %dx%d\r\n", w, h); cfg += line;
	cfg += "setvar gfx_fullscreen = 1.00\r\n";
	for (auto &v : s2QualityDefaults) { snprintf(line, sizeof line, "setvar %s = %s\r\n", v[0], v[1]); cfg += line; }
	mkdir((dir + "/cfg").c_str(), 0755);
	if (FILE *o = fopen((dir + "/cfg/config.cfg").c_str(), "wb")) { fwrite(cfg.data(), 1, cfg.size(), o); fclose(o); }
	if (FILE *o = fopen(marker.c_str(), "wb")) fclose(o);
}

// Copy a Silent Storm installation (GOG or Steam folder) into the app's data folder. APFS clones the files when
// source and destination share a volume, so this takes no extra space there.
static bool S2ImportGameFolder(const std::string &dest)
{
	NSOpenPanel *p = [NSOpenPanel openPanel];
	p.canChooseDirectories = YES; p.canChooseFiles = NO; p.allowsMultipleSelection = NO;
	p.message = @"Choose your Silent Storm game folder (the one containing game.db, from GOG or Steam).";
	p.prompt = @"Use This Folder";
	if ([p runModal] != NSModalResponseOK) return false;
	NSString *src = p.URL.path;
	if (!S2HasGameData(src.UTF8String))
	{
		NSAlert *a = [NSAlert new]; a.messageText = @"That folder has no game.db and res folder."; [a runModal];
		return false;
	}
	NSFileManager *fm = NSFileManager.defaultManager;
	NSString *d = [NSString stringWithUTF8String:dest.c_str()];
	[fm createDirectoryAtPath:[d stringByDeletingLastPathComponent] withIntermediateDirectories:YES attributes:nil error:nil];
	NSError *err = nil;
	if (![fm copyItemAtPath:src toPath:d error:&err])
	{
		NSAlert *a = [NSAlert new]; a.messageText = @"Copying the game failed"; a.informativeText = err.localizedDescription; [a runModal];
		return false;
	}
	// leftovers from Windows wrappers would shadow nothing here, but keep the folder clean
	for (NSString *junk in @[ @"d3d9.dll", @"dxvk.conf" ]) [fm removeItemAtPath:[d stringByAppendingPathComponent:junk] error:nil];
	return true;
}

void S2RequestQuit();

@interface S2MenuTarget : NSObject
@end
@implementation S2MenuTarget
- (void)s2settings:(id)sender { S2SettingsShow(); }
- (void)s2toggleGraphics:(id)sender { S2ToggleGraphicsWithNotice(); }
- (void)s2keyHelp:(id)sender { S2KeyHelpToggle(); }
- (BOOL)validateMenuItem:(NSMenuItem *)item
{
	if (item.action == @selector(s2toggleGraphics:)) item.title = S2OriginalGraphics() ? @"Switch to Enhanced Graphics" : @"Switch to Original Graphics";
	return YES;
}
// quit through the engine's own exit path, so it saves config.cfg and closes cleanly
- (void)s2quit:(id)sender { S2RequestQuit(); }
- (void)s2openGameFolder:(id)sender { [NSWorkspace.sharedWorkspace openURL:[NSURL fileURLWithPath:[NSString stringWithUTF8String:S2GameDirectory()]]]; }
@end
static S2MenuTarget *s2menuTarget;

// Quit from the Dock, an Apple Event or logout goes through the engine's exit path too: it saves config.cfg,
// removes the working save slot and shuts the device down, then main returns
@interface S2AppDelegate : NSObject <NSApplicationDelegate>
@end
@implementation S2AppDelegate
- (NSApplicationTerminateReply)applicationShouldTerminate:(NSApplication *)sender { S2RequestQuit(); return NSTerminateCancel; }
@end
static S2AppDelegate *s2appDelegate;

static void S2BuildMenu()
{
	s2menuTarget = [S2MenuTarget new];
	NSMenu *bar = [NSMenu new];
	NSMenuItem *appItem = [NSMenuItem new]; [bar addItem:appItem];
	NSMenu *app = [NSMenu new];
	[app addItemWithTitle:@"About Silent Storm" action:@selector(orderFrontStandardAboutPanel:) keyEquivalent:@""];
	[app addItem:[NSMenuItem separatorItem]];
	[app addItemWithTitle:@"Settings…" action:@selector(s2settings:) keyEquivalent:@","].target = s2menuTarget;
	NSMenuItem *graphics = [app addItemWithTitle:@"Switch to Original Graphics" action:@selector(s2toggleGraphics:) keyEquivalent:@"g"];
	graphics.target = s2menuTarget;
	graphics.keyEquivalentModifierMask = NSEventModifierFlagCommand;	// F9 does the same in the game window
	[app addItemWithTitle:@"Show Game Folder in Finder" action:@selector(s2openGameFolder:) keyEquivalent:@""].target = s2menuTarget;
	[app addItem:[NSMenuItem separatorItem]];
	[app addItemWithTitle:@"Hide Silent Storm" action:@selector(hide:) keyEquivalent:@"h"];
	[app addItem:[NSMenuItem separatorItem]];
	[app addItemWithTitle:@"Quit Silent Storm" action:@selector(s2quit:) keyEquivalent:@"q"].target = s2menuTarget;
	appItem.submenu = app;
	NSMenuItem *winItem = [NSMenuItem new]; [bar addItem:winItem];
	NSMenu *win = [[NSMenu alloc] initWithTitle:@"Window"];
	[win addItemWithTitle:@"Enter Full Screen" action:@selector(toggleFullScreen:) keyEquivalent:@"f"];
	[win addItemWithTitle:@"Minimize" action:@selector(performMiniaturize:) keyEquivalent:@"m"];
	winItem.submenu = win;
	NSMenuItem *helpItem = [NSMenuItem new]; [bar addItem:helpItem];
	NSMenu *help = [[NSMenu alloc] initWithTitle:@"Help"];
	[help addItemWithTitle:@"Keyboard Shortcuts (F1)" action:@selector(s2keyHelp:) keyEquivalent:@"/"].target = s2menuTarget;
	NSMenuItem *settingsHint = [help addItemWithTitle:@"Every setting is in Silent Storm > Settings (⌘,)" action:nil keyEquivalent:@""];
	settingsHint.enabled = NO;
	helpItem.submenu = help;
	NSApp.mainMenu = bar;
	NSApp.windowsMenu = win;
	NSApp.helpMenu = help;
}

int main(int argc, char **argv)
{
	@autoreleasepool
	{
		[NSApplication sharedApplication];
		// test runs stay out of the Dock and the app switcher: a hidden process must never be mistaken for the game
		[NSApp setActivationPolicy:getenv("S2_HEADLESS") ? NSApplicationActivationPolicyProhibited : getenv("S2_NO_ACTIVATE") ? NSApplicationActivationPolicyAccessory : NSApplicationActivationPolicyRegular];
		S2BuildMenu();
		s2appDelegate = [S2AppDelegate new];
		NSApp.delegate = s2appDelegate;
		[NSApp finishLaunching];

		s2gameDir = S2FindGameDirectory(argc, argv);
		if (!S2HasGameData(s2gameDir) && s2gameDir.find("/Application Support/") != std::string::npos)
			S2ImportGameFolder(s2gameDir);
		if (S2HasGameData(s2gameDir)) S2WriteMacDefaults(s2gameDir);
		S2SettingsLoad();
		if (!S2HasGameData(s2gameDir) || chdir(s2gameDir.c_str()) != 0)
		{
			NSAlert *a = [NSAlert new];
			a.messageText = @"Silent Storm game files not found";
			a.informativeText = [NSString stringWithFormat:@"Looked in:\n%s\n\nInstall the game data (from your GOG or Steam copy) there, or start with --game-dir <folder>.", s2gameDir.c_str()];
			[a runModal];
			return 1;
		}
	}
	// pass engine switches through (-window, -load, -harness, ...), skipping our own
	std::string cmd;
	for (int i = 1; i < argc; ++i)
	{
		if (!strcmp(argv[i], "--game-dir")) { ++i; continue; }
		if (!strncmp(argv[i], "-psn_", 5) || !strncmp(argv[i], "-NS", 3)) { if (!strncmp(argv[i], "-NS", 3)) ++i; continue; }
		if (!cmd.empty()) cmd += ' ';
		cmd += argv[i];
	}
	return WinMain((HINSTANCE)1, nullptr, (LPSTR)cmd.c_str(), 5);
}
