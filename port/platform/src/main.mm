static std::string s2gameDir;
const char *S2GameDirectory() { return s2gameDir.c_str(); }
const char *S2ConfigPath(const char *base)
{
	static std::string path;
	path = std::string(".\\cfg\\") + base;
	return path.c_str();
}
static bool S2FileExists(const std::string &p) { struct stat st; return stat(p.c_str(), &st) == 0; }
static bool S2HasGameData(const std::string &dir)
{
	if (dir.empty() || !S2FileExists(dir + "/res")) return false;
	return S2FileExists(dir + "/game.db");
}

// The game data (the user's own copy, from GOG or Steam) is looked up in this order:
//   1. --game-dir <path> or the SS_GAME_DIR environment variable
//   2. Silent Storm.app/Contents/Resources/Game
//   3. ~/Library/Application Support/Silent Storm/Silent Storm
static std::string S2FindGameDirectory(int argc, char **argv)
{
	for (int i = 1; i + 1 < argc; ++i) if (!strcmp(argv[i], "--game-dir")) return argv[i + 1];
	if (const char *e = getenv("SS_GAME_DIR")) return e;
	std::string bundled = std::string(NSBundle.mainBundle.resourcePath.UTF8String) + "/Game";
	if (S2HasGameData(bundled)) return bundled;
	NSString *support = [NSSearchPathForDirectoriesInDomains(NSApplicationSupportDirectory, NSUserDomainMask, YES) firstObject];
	return std::string(support.UTF8String) + "/Silent Storm/Silent Storm";
}

